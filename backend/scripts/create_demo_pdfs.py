def main() -> None:
    print(f"Generating demo PDFs in: {OUT_DIR}")
    build_haas_vf2()
    build_fanuc_oi_mf()
    build_kuka_kr6()
    print("\nDone. Upload these files via the MechMind admin UI to enable RAG queries.")


if __name__ == "__main__":
    main()
